CREATE TYPE org_kind          AS ENUM ('cliente', 'fabricante');
CREATE TYPE user_role         AS ENUM ('operador', 'tecnico', 'assistencia', 'gestor');
CREATE TYPE incident_severity AS ENUM ('baixa', 'media', 'critica');
CREATE TYPE incident_status   AS ENUM ('recebida', 'em_analise', 'resolvida');
CREATE TYPE attachment_kind   AS ENUM ('foto', 'audio', 'video');

CREATE TABLE organizations (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name       text NOT NULL,
    kind       org_kind NOT NULL,
    -- how a second manufacturer finds a client that's already registered, the API also
    -- checks the check digit
    nif        text NOT NULL UNIQUE CHECK (nif ~ '^[0-9]{9}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, kind)  -- target for the FKs that pin an organization's kind
);

-- Which manufacturers serve which clients: a client can buy from several manufacturers, and a
-- manufacturer has many clients. The *_kind columns only exist so the FKs can check that each
-- side is the right kind of organization.
CREATE TABLE client_manufacturers (
    client_id         uuid NOT NULL,
    client_kind       org_kind NOT NULL DEFAULT 'cliente' CHECK (client_kind = 'cliente'),
    manufacturer_id   uuid NOT NULL,
    manufacturer_kind org_kind NOT NULL DEFAULT 'fabricante'
                      CHECK (manufacturer_kind = 'fabricante'),
    created_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (client_id, manufacturer_id),
    FOREIGN KEY (client_id, client_kind) REFERENCES organizations (id, kind),
    FOREIGN KEY (manufacturer_id, manufacturer_kind) REFERENCES organizations (id, kind)
);
CREATE INDEX client_manufacturers_manufacturer_idx ON client_manufacturers (manufacturer_id);

CREATE TABLE users (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id      uuid NOT NULL,
    organization_kind    org_kind NOT NULL,  -- copied so the CHECK below can see it
    name                 text NOT NULL,
    email                text NOT NULL,
    password_hash        text NOT NULL,
    role                 user_role NOT NULL,
    -- created with a temporary password, the API only lets the account change it
    must_change_password boolean NOT NULL DEFAULT false,
    created_at           timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (organization_id, organization_kind) REFERENCES organizations (id, kind),
    CONSTRAINT users_role_matches_organization CHECK (CASE organization_kind
        WHEN 'cliente'    THEN role IN ('operador', 'gestor')
        WHEN 'fabricante' THEN role IN ('assistencia', 'tecnico', 'gestor')
    END)
);
CREATE UNIQUE INDEX users_email_key ON users (lower(email));
CREATE INDEX users_organization_idx ON users (organization_id);

CREATE TABLE machines (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id uuid NOT NULL,  -- the client that owns it
    manufacturer_id uuid NOT NULL,  -- who made it and services it
    serial_number   text NOT NULL UNIQUE,
    model           text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    -- a manufacturer can only register machines at a client it serves
    FOREIGN KEY (organization_id, manufacturer_id)
        REFERENCES client_manufacturers (client_id, manufacturer_id),
    UNIQUE (id, organization_id, manufacturer_id)  -- target for the composite FK below
);
CREATE INDEX machines_organization_idx ON machines (organization_id);
CREATE INDEX machines_manufacturer_idx ON machines (manufacturer_id);

CREATE TABLE incidents (
    id              uuid PRIMARY KEY,  -- generated by the client
    organization_id uuid NOT NULL,     -- owner of the machine, kept consistent by the FK
    -- whose support staff take it, for now always the machine's manufacturer
    handled_by      uuid NOT NULL,
    machine_id      uuid NOT NULL,
    author_id       uuid NOT NULL REFERENCES users (id),
    description     text NOT NULL DEFAULT '',  -- may be empty if reported by voice
    severity        incident_severity NOT NULL,
    status          incident_status NOT NULL DEFAULT 'recebida',
    assigned_to     uuid REFERENCES users (id),  -- technician picked by support staff
    latitude        double precision,
    longitude       double precision,
    accuracy_m      real,
    reported_at     timestamptz NOT NULL,      -- device clock, when it was created offline
    created_at      timestamptz NOT NULL DEFAULT now(),  -- server insertion time
    updated_at      timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (machine_id, organization_id, handled_by)
        REFERENCES machines (id, organization_id, manufacturer_id),
    CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CHECK (latitude  BETWEEN -90  AND 90),
    CHECK (longitude BETWEEN -180 AND 180),
    CHECK (accuracy_m >= 0)
);
-- incremental sync and org isolation, keyset-paginated on (updated_at, id), for the client's
-- staff and for the manufacturer's
CREATE INDEX incidents_org_sync_idx     ON incidents (organization_id, updated_at, id);
CREATE INDEX incidents_handler_sync_idx ON incidents (handled_by, updated_at, id);
CREATE INDEX incidents_machine_idx  ON incidents (machine_id, created_at DESC);
-- support triage queue: open incidents, most severe first
CREATE INDEX incidents_triage_idx   ON incidents (severity DESC, created_at)
    WHERE status <> 'resolvida';
-- a technician's queue, and their open incident count in GET /technicians
CREATE INDEX incidents_assignee_idx ON incidents (assigned_to, updated_at, id)
    WHERE assigned_to IS NOT NULL;

CREATE TABLE attachments (
    id           uuid PRIMARY KEY,  -- generated by the client, idempotent upload
    incident_id  uuid NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    kind         attachment_kind NOT NULL,
    content_type text NOT NULL,
    storage_key  text NOT NULL UNIQUE,
    size_bytes   bigint NOT NULL CHECK (size_bytes > 0),
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_incident_idx ON attachments (incident_id);

CREATE TABLE incident_updates (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id uuid NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id   uuid NOT NULL REFERENCES users (id),
    message     text,
    new_status  incident_status,
    assigned_to uuid REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (message IS NOT NULL OR new_status IS NOT NULL OR assigned_to IS NOT NULL)
);
CREATE INDEX incident_updates_incident_idx ON incident_updates (incident_id, created_at);
-- every incident a technician has ever been assigned, they keep seeing those after a reassignment
CREATE INDEX incident_updates_assignee_idx ON incident_updates (assigned_to, incident_id)
    WHERE assigned_to IS NOT NULL;

CREATE TABLE devices (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    fcm_token    text NOT NULL UNIQUE,
    last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX devices_user_idx ON devices (user_id);

CREATE TABLE refresh_tokens (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash bytea NOT NULL UNIQUE,  -- SHA-256 of the token, never the token itself
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);

-- Any change to an incident bumps updated_at, so updated_since can't miss it.
CREATE FUNCTION incidents_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

CREATE TRIGGER incidents_touch_updated_at
    BEFORE UPDATE ON incidents
    FOR EACH ROW EXECUTE FUNCTION incidents_touch();

-- A new update applies its status and assignee (if any) and, via the trigger above, bumps
-- updated_at.
CREATE FUNCTION incident_updates_apply() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE incidents
       SET status      = COALESCE(NEW.new_status, status),
           assigned_to = COALESCE(NEW.assigned_to, assigned_to)
     WHERE id = NEW.incident_id;
    RETURN NULL;
END $$;

CREATE TRIGGER incident_updates_after_insert
    AFTER INSERT ON incident_updates
    FOR EACH ROW EXECUTE FUNCTION incident_updates_apply();

CREATE FUNCTION attachments_touch_incident() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE incidents SET updated_at = now() WHERE id = NEW.incident_id;
    RETURN NULL;
END $$;

CREATE TRIGGER attachments_after_insert
    AFTER INSERT ON attachments
    FOR EACH ROW EXECUTE FUNCTION attachments_touch_incident();