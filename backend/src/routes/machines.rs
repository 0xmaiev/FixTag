use {
    crate::{
        Result,
        auth::CurrentUser,
        error::{Error, ErrorBody},
        machine_scope,
        models::Machine,
        state::State as AppState,
    },
    axum::{
        Extension, Json,
        extract::{Path, Query, State},
        http::StatusCode,
    },
    serde::Deserialize,
    std::sync::Arc,
    uuid::Uuid,
};

#[derive(Deserialize, utoipa::IntoParams)]
#[into_params(parameter_in = Query)]
pub struct MachineQueryParams {
    /// Exact serial number, e.g. the value read from the QR code
    pub serial_number: Option<String>,
}

#[derive(Deserialize, utoipa::ToSchema)]
pub struct MachineInput {
    /// The client that owns the machine, one the caller's manufacturer serves. Can't change
    /// later. The manufacturer is always the caller's organization
    pub organization_id: Uuid,
    /// Also what the QR code on the machine encodes, unique across every client
    pub serial_number: String,
    pub model: String,
}

/// Machines visible to the caller: every machine of their client, whoever made it, or the ones
/// their manufacturer made, at every client. Small enough to cache whole in Room, so QR lookups
/// also work offline.
#[utoipa::path(
    get,
    path = "/machines",
    tag = "machines",
    params(MachineQueryParams),
    responses((status = 200, body = Vec<Machine>)),
    security(("bearer" = [])),
)]
pub async fn fetch_machines(
    State(state): State<Arc<AppState>>,
    Extension(user): Extension<CurrentUser>,
    Query(params): Query<MachineQueryParams>,
) -> Result<Json<Vec<Machine>>> {
    let scope = user.scope();
    let machines = sqlx::query_as::<_, Machine>(concat!(
        "SELECT m.id, m.organization_id, m.manufacturer_id, m.serial_number, m.model, m.created_at
           FROM machines m
          WHERE ",
        machine_scope!(),
        " AND ($3::text IS NULL OR m.serial_number = $3)
          ORDER BY m.serial_number"
    ))
    .bind(scope.client())
    .bind(scope.manufacturer())
    .bind(params.serial_number.as_deref().map(str::trim))
    .fetch_all(&state.db)
    .await?;

    Ok(Json(machines))
}

/// PUT, registers a machine the caller's manufacturer made, at a client it serves, with the id
/// generated by the app, like incidents, so it can be registered offline. Sending it again edits
/// the serial number and model. Only a manufacturer's support staff can.
#[utoipa::path(
    put,
    path = "/machines/{id}",
    tag = "machines",
    params(("id" = Uuid, Path, description = "Generated by the client")),
    request_body = MachineInput,
    responses(
        (status = 201, description = "Registered", body = Machine),
        (status = 200, description = "Already existed, edits applied", body = Machine),
        (status = 400, description = "Empty fields, or organization_id isn't a client the caller's manufacturer serves", body = ErrorBody),
        (status = 403, description = "Not a manufacturer's support staff", body = ErrorBody),
        (status = 404, description = "The id belongs to another manufacturer's machine", body = ErrorBody),
        (status = 409, description = "serial_number belongs to another machine, or organization_id differs from the stored machine", body = ErrorBody),
    ),
    security(("bearer" = [])),
)]
pub async fn create_machine(
    State(state): State<Arc<AppState>>,
    Extension(user): Extension<CurrentUser>,
    Path(id): Path<Uuid>,
    Json(input): Json<MachineInput>,
) -> Result<(StatusCode, Json<Machine>)> {
    if !user.is_support() {
        return Err(Error::Forbidden(
            "only a manufacturer's support staff can register machines".into(),
        ));
    }
    let serial_number = input.serial_number.trim();
    let model = input.model.trim();
    if serial_number.is_empty() || model.is_empty() {
        return Err(Error::BadRequest(
            "serial_number and model can't be empty".into(),
        ));
    }

    // the foreign key would catch it too, this just gives a clearer error
    let serves_client: bool = sqlx::query_scalar(
        "SELECT EXISTS (
             SELECT 1 FROM client_manufacturers WHERE client_id = $1 AND manufacturer_id = $2
         )",
    )
    .bind(input.organization_id)
    .bind(user.organization_id)
    .fetch_one(&state.db)
    .await?;
    if !serves_client {
        return Err(Error::BadRequest(
            "organization_id must be a client your organization serves".into(),
        ));
    }

    // the unique constraint would catch it too, this just gives a clearer error
    let taken: bool = sqlx::query_scalar(
        "SELECT EXISTS (SELECT 1 FROM machines WHERE serial_number = $1 AND id <> $2)",
    )
    .bind(serial_number)
    .bind(id)
    .fetch_one(&state.db)
    .await?;
    if taken {
        return Err(Error::Conflict(
            "serial_number already belongs to another machine".into(),
        ));
    }

    let inserted = sqlx::query_as::<_, Machine>(
        "INSERT INTO machines (id, organization_id, manufacturer_id, serial_number, model)
         VALUES ($1, $2, $3, $4, $5)
         ON CONFLICT (id) DO NOTHING
         RETURNING id, organization_id, manufacturer_id, serial_number, model, created_at",
    )
    .bind(id)
    .bind(input.organization_id)
    .bind(user.organization_id)
    .bind(serial_number)
    .bind(model)
    .fetch_optional(&state.db)
    .await?;
    if let Some(machine) = inserted {
        return Ok((StatusCode::CREATED, Json(machine)));
    }

    // a retry, or an edit after the first sync
    let (organization_id, manufacturer_id): (Uuid, Uuid) =
        sqlx::query_as("SELECT organization_id, manufacturer_id FROM machines WHERE id = $1")
            .bind(id)
            .fetch_one(&state.db)
            .await?;
    if manufacturer_id != user.organization_id {
        return Err(Error::NotFound);
    }
    if organization_id != input.organization_id {
        return Err(Error::Conflict("organization_id can't be changed".into()));
    }
    let machine = sqlx::query_as::<_, Machine>(
        "UPDATE machines
            SET serial_number = $2, model = $3
          WHERE id = $1
         RETURNING id, organization_id, manufacturer_id, serial_number, model, created_at",
    )
    .bind(id)
    .bind(serial_number)
    .bind(model)
    .fetch_one(&state.db)
    .await?;
    Ok((StatusCode::OK, Json(machine)))
}
